# Значение арифметического выражения
# 15⋅343²⁰³¹+7⋅49¹¹⁴²−3⋅7¹¹¹+7²²²−16809
# записали в системе счисления с основанием 7. Определите разницу между
# количеством чётных и нечётных цифр в записи этого числа.

a = 15*343**2031 + 7*49**1142 - 3*7**111 + 7**222 - 16809
even = 0
odd = 0
while a > 0:
    digit = a % 7
    if digit % 2 == 0:
        even += 1
    else:
        odd += 1
    a //= 7
print(even - odd)

