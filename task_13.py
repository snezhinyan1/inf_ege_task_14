# Задача №13
# Сколько существует чисел, таких что в пятеричной системе содержит 4 цифры, в
# троичной системе содержит 5 цифр, а в шестнадцатеричной системе оканчиваются
# на D.

count = 0
for n in range(5**3, 5**4):
    if 3**4 <= n < 3**5 and n % 16 == 13:
        count += 1
print(count)

