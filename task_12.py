# Задание №12
# Запись числа N в системе счисления c основанием 6 содержит две цифры, запись
# этого числа в системе счисления c основанием 5 содержит три цифры, а запись в
# системе счисления c основанием 11 заканчивается на 1. Чему равно N? Запишите
# ответ в десятичной системе счисления.

for n in range(6, 6**2):
    if 5**2 <= n < 5**3 and n % 11 == 1:
        print(n)

