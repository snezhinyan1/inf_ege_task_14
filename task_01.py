# Задача № 1
# Значение арифметического выражения 4⁶⁴⁴+4³²²+16³⁵−64³ записали в 4-ричной
# системе счисления. Сколько цифр «3» содержится в этой записи?

a = 4**644 + 4**322 + 16**35 - 64**3
count = 0
while a > 0:
    digit = a % 4
    if digit == 3:
        count += 1
    a //= 4
print(count)

# Ответ: 61
