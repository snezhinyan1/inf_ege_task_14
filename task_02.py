# Задача № 2
# Значение арифметического выражения 6⋅512¹⁸⁰+7⋅64¹⁸¹+3⋅8¹⁸⁴+5⋅8¹²⁵−65 записали в
# системе счисления с основанием 64. Сколько значащих нулей содержится в этой
# записи?

a = 6*512**180 + 7*64**181 + 3*8**184 + 5*8**125 - 65
count = 0
while a > 0:
    digit = a % 64
    if digit == 0:
        count += 1
    a //= 64
print(count)

# Ответ: 205
