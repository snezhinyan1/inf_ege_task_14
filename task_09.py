# Задача №9
# Значение арифметического выражения 75³¹⁴+75¹¹⁸−x, где х – натуральное число, не
# превышающее 32000, записали в 75-ричной системе счисления. Определите
# минимальное возможное количество нулей в 75-ричной записи числа, являющегося
# значением данного арифметического выражения. В ответе запишите только целое
# число.

def count_zeros(a):
    count = 0
    while a > 0:
        if a % 75 == 0:
            count += 1
        a //= 75
    return count


start = 75**314 + 75**118
print(min(count_zeros(start - x) for x in range(1, 32001)))

