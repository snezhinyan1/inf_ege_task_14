# Задача №8
# При каком наименьшем натуральном значении переменной x в
# выражении 81²⁰−9ˣ+50 сумма цифр в девятеричной записи числа равна 138?

# При x > 40 значение выражения отрицательно (81²⁰ = 9⁴⁰).
for x in range(1, 41):
    a = 81**20 - 9**x + 50
    total = 0
    while a > 0:
        total += a % 9
        a //= 9
    if total == 138:
        print(x)
        break

# Ответ: 24
