# Задача №10
# Значение арифметического выражения 5²⁰²⁵+5²⁰⁰−х, где х – натуральное число в
# диапазоне от 2 до 2025, записали в системе счисления с основанием 5. Определите
# максимальное значение x, при котором данная запись содержит наибольшее
# количество цифр «4».

start = 5**2025 + 5**200
best_count = -1
for x in range(2025, 1, -1):
    a = start - x
    count = 0
    while a > 0:
        if a % 5 == 4:
            count += 1
        a //= 5
    if count > best_count:
        best_count = count
        best_x = x
print(best_x)

