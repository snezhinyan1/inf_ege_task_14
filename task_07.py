# Задача № 7
# Значение арифметического выражения 5¹⁵⁰+5¹³⁵−x, где x – целое положительное
# число, не превышающее 5555, записали в 5-ричной системе счисления. Определите
# наибольшее значение x, при котором в 5-ричной записи числа, являющегося
# значением данного арифметического выражения, содержится ровно 134 цифры 4. В
# ответе запишите число в десятичной системе счисления.

for x in range(5555, 0, -1):
    a = 5**150 + 5**135 - x
    count = 0
    while a > 0:
        if a % 5 == 4:
            count += 1
        a //= 5
    if count == 134:
        print(x)
        break

