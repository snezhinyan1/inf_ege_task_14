# Задача № 3
# Определите в 121-ричной записи числа количество цифр с числовым значением, не
# менее 64 и не более 104:
# 39⋅121³¹⁹+46⋅11⁹¹³−15⋅1331¹⁵−1993

a = 39*121**319 + 46*11**913 - 15*1331**15 - 1993
count = 0
while a > 0:
    digit = a % 121
    if 64 <= digit <= 104:
        count += 1
    a //= 121
print(count)

# Ответ: 3
