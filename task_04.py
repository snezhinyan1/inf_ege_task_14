# Задача №4
# Значение арифметического выражения
# 2⋅2187⁵⁶⁷+729⁵⁶⁶−2⋅243⁵⁶⁵+81⁵⁶⁴−2⋅27⁵⁶³−6561
# записали в системе счисления с основанием 27. Определите в 27-ричной записи
# числа количество цифр с чётным числовым значением, превышающим 9.

a = 2*2187**567 + 729**566 - 2*243**565 + 81**564 - 2*27**563 - 6561
count = 0
while a > 0:
    digit = a % 27
    if digit > 9 and digit % 2 == 0:
        count += 1
    a //= 27
print(count)

# Ответ: 940
