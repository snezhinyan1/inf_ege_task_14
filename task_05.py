# Значение арифметического выражения 5⋅216³⁰³¹+4⋅36³⁰⁴²−3⋅6³⁰⁵³−3064 записали в
# системе счисления с основанием 6. Определите сумму цифр в записи этого числа.

a = 5*216**3031 + 4*36**3042 - 3*6**3053 - 3064
total = 0
while a > 0:
    total += a % 6
    a //= 6
print(total)

